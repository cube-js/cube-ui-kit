/**
 * The runtime source under `src/`, without comments: no specs, stories,
 * fixtures or the `stories/` guides, which the CI planner doesn't run this
 * spec for, and no comments, which only mention a token.
 */
function readRuntimeSource() {
  const src = join(ROOT, 'src');

  return readdirSync(src, { recursive: true, encoding: 'utf8' })
    .filter(
      (file) =>
        /\.tsx?$/.test(file) &&
        !/\.(test|spec|stories|test-d|fixture)\.tsx?$|(^|\/)(test|stories)\//.test(
          file,
        ),
    )
    .map((file) =>
      readFileSync(join(src, file), 'utf8')
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .replace(/(^|[^:'"`\\])\/\/.*$/gm, '$1'),
    )
    .join('\n');
}

/** A `$name` or `#name` token, as a regular expression source. */
function tokenPattern(token: string) {
  return `\\${token[0]}${token.slice(1)}(?![\\w-])`;
}

/**
 * Whether `source` sets `token` (a styles or tokens key, a raw `--name` key,
 * a CSS declaration or `setProperty`), or reads it with a fallback,
 * `($name, 0px)`, which is how a component takes a token its consumer may set.
 * A key is matched as Prettier writes one, with no space before the colon, so
 * a ternary's `'$name' : …` is not one; `max($name, …)` is no fallback.
 */
function isSetOrDefaulted(source: string, token: string) {
  const variable =
    token[0] === '#' ? `${token.slice(1)}(?:-color)?` : token.slice(1);

  return [
    `(?<![\\w-])[\\[\`'"]*${tokenPattern(token)}[\`'"\\]]*:(?!:)`,
    `[\`'"]--${variable}[\`'"][:,]`,
    `(?<![\\w(-])--${variable}\\s*:`,
    `(?<![\\w-])\\(\\s*${tokenPattern(token)}\\s*,`,
  ].some((pattern) => new RegExp(pattern).test(source));
}

/**
 * Lint `files` in a throwaway consumer project that installs this checkout as
 * `@cube-dev/ui-kit` and extends its `tasty.config.ts`, the way Cube Cloud
 * does. Returns the trimmed source line of each diagnostic from `rules`.
 */
function lintConsumer(rules: string[], files: Record<string, string>) {
  const dir = mkdtempSync(join(tmpdir(), 'ui-kit-consumer-'));

  try {
    mkdirSync(join(dir, 'node_modules/@cube-dev'), { recursive: true });
    symlinkSync(ROOT, join(dir, 'node_modules/@cube-dev/ui-kit'), 'dir');
    writeFileSync(join(dir, 'package.json'), '{ "private": true }');
    writeFileSync(
      join(dir, 'tasty.config.ts'),
      "export default { extends: '@cube-dev/ui-kit' };",
    );
    writeFileSync(
      join(dir, '.oxlintrc.json'),
      JSON.stringify({
        categories: { correctness: 'off' },
        plugins: [],
        jsPlugins: [
          {
            name: 'tasty',
            specifier: join(
              ROOT,
              'node_modules/@tenphi/eslint-plugin-tasty/dist/index.js',
            ),
          },
        ],
        rules: Object.fromEntries(
          rules.map((rule) => [`tasty/${rule}`, 'error']),
        ),
      }),
    );

    for (const [name, source] of Object.entries(files)) {
      writeFileSync(join(dir, name), source);
    }

    // Name the files: given `.`, oxlint follows the symlink into this
    // checkout and lints its consumer type tests as well.
    const result = spawnSync(
      join(ROOT, 'node_modules/.bin/oxlint'),
      ['-c', '.oxlintrc.json', '-f', 'json', ...Object.keys(files)],
      { cwd: dir, encoding: 'utf8' },
    );
    if (result.error) throw result.error;

    let report: {
      diagnostics: {
        code: string;
        filename: string;
        labels: { span: { line: number } }[];
      }[];
    };

    try {
      report = JSON.parse(result.stdout);
    } catch {
      throw new Error(`oxlint failed:\n${result.stdout}\n${result.stderr}`);
    }

    return report.diagnostics
      .filter((diagnostic) =>
        rules.some((rule) => diagnostic.code === `tasty(${rule})`),
      )
      .map((diagnostic) => {
        const lines = readFileSync(
          join(dir, diagnostic.filename),
          'utf8',
        ).split('\n');

        return lines[diagnostic.labels[0].span.line - 1].trim();
      })
      .sort();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

describe('tasty.config.ts', () => {
  const runtime = collectRuntimeNames();

  if (process.env.UPDATE_TASTY_CONFIG) {
    it('regenerates tasty.config.generated.ts', () => {
      writeFileSync(GENERATED, serialize(runtime), 'utf8');
    });

    return;
  }

  // The ESLint plugin checks consumers' tokens, states, presets and recipes
  // against these lists: a name missing from them reports wherever it is
  // used, and a stale one hides a style that renders nothing.
  it('lists the names UI Kit defines at runtime', () => {
    expect(
      runtimeNames,
      'tasty.config.generated.ts is stale: run `pnpm generate:tasty-config`',
    ).toEqual(runtime);
    // `tokens` adds the hand list; the other three are the generated lists.
    expect(tastyConfig).toMatchObject({
      tokens: expect.arrayContaining(runtimeNames.tokens),
      states: runtimeNames.states,
      presets: runtimeNames.presets,
      recipes: runtimeNames.recipes,
    });
  });

  it('reports only names UI Kit never defined, for a consumer that extends it', () => {
    const reported = lintConsumer(
      [
        'valid-color-token',
        'valid-custom-property',
        'valid-preset',
        'valid-recipe',
        'no-unknown-state-alias',
      ],
      { 'Names.tsx': NAMES },
    );

    expect(reported).toEqual(
      [
        "fill: '#pink-01',",
        "color: { '': '#dark', '@mobile': '#surface' },",
        "width: '$fade-width',",
        "height: '$tab-indicator-size',",
        "preset: 'inline',",
      ].sort(),
    );
  }, 30_000);

  // Every listed component token is set by a component, or read with a
  // fallback when an app may set it: a name that is neither renders an
  // invalid `var()` wherever it is read, and the list keeps the lint quiet
  // about it. `pnpm check:component-tokens` checks the published ones are
  // documented, in the lint job, which runs for a docs-only PR too.
  it('lists only component tokens UI Kit sets, each once', () => {
    const source = readRuntimeSource();
    const listed = [...componentTokens, ...internalConfig.tokens];

    expect({
      unset: listed.filter((token) => !isSetOrDefaulted(source, token)),
      listedTwice: listed.filter(
        (token, index) =>
          listed.indexOf(token) !== index ||
          runtimeNames.tokens.includes(token),
      ),
    }).toEqual({ unset: [], listedTwice: [] });
  });

  // A consumer that extends this config gets `protectedComponents`, so
  // restyling a component reports, its primitives stay open, containers keep
  // the props that lay out their content, a placeholder keeps its `radius`,
  // and a component's own prop named like a style passes, while that name on
  // a component that doesn't own it (`<Button filter>`) is reported. A
  // sub-component counts as its export (`Button.Split`) unless the config
  // names it (`Button.Group`).
  it('protects components for a consumer that extends it', () => {
    const reported = lintConsumer(['no-protected-restyle'], {
      'CopyButton.tsx': COPY_BUTTON,
      'Consumer.tsx': CONSUMER,
    });

    expect(reported).toEqual(
      [
        "export const DangerButton = tasty(Button, { styles: { fill: '#danger' } });",
        "export const CopyDangerButton = tasty(CopyButton, { styles: { fill: '#danger' } });",
        "<Button styles={{ fill: '#danger' }} />",
        '<Button fill="#danger" />',
        "<ItemButton styles={{ padding: '2x' }} />",
        "<ComboBox inputStyles={{ padding: '2x' }} />",
        "<CopyButton styles={{ fill: '#danger' }} />",
        '<ComboBox fill="#danger" />',
        '<Button filter="grayscale(1)" />',
        '<Button.Split fill="#danger" />',
        '<Card fill="#danger" />',
        '<Alert fill="#danger" />',
        '<Placeholder padding="2x" />',
      ].sort(),
    );
  }, 30_000);
});
