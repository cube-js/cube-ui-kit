/**
 * The names UI Kit defines at runtime, which `tasty.config.ts` publishes for
 * the ESLint plugin to check consumers' styles against.
 */
function collectRuntimeNames() {
  return {
    tokens: Object.keys(getTokens())
      .filter((name) => name.startsWith('#') || name.startsWith('$'))
      .sort(),
    states: Object.keys(getGlobalPredefinedStates()).sort(),
    presets: Object.keys(TYPOGRAPHY_PRESETS).sort(),
    recipes: Object.keys(getGlobalRecipes() ?? {}).sort(),
  };
}

function serialize(names: Record<string, string[]>) {
  const lists = Object.entries(names)
    .map(
      ([key, list]) =>
        `  ${key}: [\n${list.map((name) => `    '${name}',\n`).join('')}  ],\n`,
    )
    .join('');

  return `// AUTOGENERATED by \`pnpm generate:tasty-config\`. Do not edit by hand.
//
// What UI Kit defines at runtime, published through \`tasty.config.ts\`: the
// tokens \`getTokens()\` emits, the state aliases and recipes \`<Root>\`
// registers, and the typography presets. \`src/tokens/tasty-config.test.ts\`
// fails when this file is stale.

export const runtimeNames = {
${lists}};
`;
}

